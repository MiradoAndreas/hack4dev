"""Exercise rejection gates and unlabeled monitoring with development fixtures.

Test-only contracts are not data-owner confirmations and are kept in a temporary
directory. No independent-test score is generated by these checks.
"""
import json
from pathlib import Path
from tempfile import TemporaryDirectory

import pandas as pd

from scripts.improve_25 import ROOT, OUT
from scripts.independent_evaluation import evaluate


def check():
    with TemporaryDirectory(prefix='independent-evaluation-check-') as name:
        folder = Path(name)
        table = pd.read_parquet(ROOT / 'data/preprocessed_age_labels/amsterdam_supervised_features.parquet')
        table = table.merge(pd.read_parquet(OUT / 'derived_features.parquet'), left_on='location_id', right_index=True, validate='one_to_one').iloc[:200]
        path = folder / 'development_fixture.parquet'
        table.to_parquet(path, index=False)
        contract = json.loads((OUT / 'data_contract_template.json').read_text())
        contract_path = folder / 'test_only_contract.json'
        contract_path.write_text(json.dumps(contract))
        try:
            evaluate(path, contract_path, folder / 'forbidden.json')
        except ValueError as error:
            assert 'Unconfirmed data contract' in str(error)
        else:
            raise AssertionError('Unconfirmed metadata was accepted')
        contract = {key: True if isinstance(value, bool) else value for key, value in contract.items()}
        contract['note'] = 'TEST FIXTURE ONLY, not scientific metadata confirmation'
        contract_path.write_text(json.dumps(contract))
        try:
            evaluate(path, contract_path, folder / 'forbidden.json')
        except ValueError as error:
            assert 'already used in development' in str(error)
        else:
            raise AssertionError('Development locations accepted as an independent test')
        renamed = table.copy()
        renamed.location_id = 'renamed:' + renamed.location_id
        renamed.to_parquet(path, index=False)
        try:
            evaluate(path, contract_path, folder / 'forbidden.json')
        except ValueError as error:
            assert 'coordinates overlap' in str(error)
        else:
            raise AssertionError('Renamed development coordinates bypassed the gate')
        table.drop(columns='age_class').to_parquet(path, index=False)
        result = evaluate(path, contract_path, folder / 'unlabeled_monitor_smoke.json', monitor=True)
        assert result['monitor_only'] and result['n_locations'] == 200
        assert 'macro_f1' not in result and len(result['drift']) > 0
        assert not (folder / 'forbidden.json').exists()
    print('PASS: metadata gate, development-ID rejection, coordinate-overlap rejection, and unlabeled monitor; no final-test score produced.')


if __name__ == '__main__':
    check()
